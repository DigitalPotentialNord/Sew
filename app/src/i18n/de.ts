export type StringKey = keyof typeof de;

export function t(key: string, values?: Readonly<Record<string, number | string | undefined>>): string {
  const raw = (de as Record<string, string>)[key] ?? key;
  if (!values) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name: string) => {
    const v = values[name];
    return v === undefined ? m : String(v);
  });
}

/** Zahl + Einheit, schön formatiert (deutsche Schreibweise). */
export function fmtMm(v: number, unit: 'mm' | 'cm' = 'mm'): string {
  if (unit === 'cm') {
    const cm = v / 10;
    return `${cm.toFixed(cm % 1 === 0 ? 0 : 1).replace('.', ',')} cm`;
  }
  return `${Math.round(v)} mm`;
}

